//! File upload contract (C14) with a local-disk object store. The `Storage` seam allows an S3 adapter later.
use axum::{body::Bytes, extract::{DefaultBodyLimit, Path, Query, State}, http::{header, HeaderMap, StatusCode}, response::{IntoResponse, Response}, routing::{get, post, put}, Json, Router};
use jsonwebtoken::{decode, encode, Algorithm, DecodingKey, EncodingKey, Header, Validation};
use serde::{Deserialize, Serialize};
use serde_json::{json, Value};
use sha2::{Digest, Sha256};
use shikkhaos_domain::permissions::Role;
use uuid::Uuid;
use crate::{audit, auth::Ctx, error::*, http::*, state::AppState};

pub fn router() -> Router<AppState> {
    Router::new()
        .route("/files/uploads", post(start))
        .route("/files/{id}/content", put(upload).layer(DefaultBodyLimit::max(26 * 1024 * 1024)))
        .route("/files/{id}/complete", post(complete))
        .route("/files/{id}/download-url", get(download_url))
        .route("/files/{id}/download", get(download))
}

pub struct FsStorage { dir: std::path::PathBuf }
impl FsStorage {
    pub fn new(dir: &str) -> Self { Self { dir: dir.into() } }
    fn path(&self, key: &str) -> ApiResult<std::path::PathBuf> {
        if key.len() != 36 || !key.chars().all(|c| c.is_ascii_hexdigit() || c == '-') { return Err(ApiError::internal()); } // keys are UUIDs only: no path traversal
        Ok(self.dir.join(key))
    }
    pub async fn put(&self, key: &str, bytes: &[u8]) -> ApiResult<()> { tokio::fs::create_dir_all(&self.dir).await.map_err(|_| ApiError::internal())?; tokio::fs::write(self.path(key)?, bytes).await.map_err(|_| ApiError::internal()) }
    pub async fn get(&self, key: &str) -> ApiResult<Vec<u8>> { tokio::fs::read(self.path(key)?).await.map_err(|_| ApiError::not_found()) }
    pub async fn delete(&self, key: &str) { if let Ok(p) = self.path(key) { let _ = tokio::fs::remove_file(p).await; } }
}

fn limits(kind: &str) -> Option<(i64, &'static [&'static str])> {
    const IMG: &[&str] = &["image/png", "image/jpeg", "image/webp"];
    const DOC: &[&str] = &["application/pdf", "image/png", "image/jpeg", "application/vnd.openxmlformats-officedocument.wordprocessingml.document", "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", "text/plain"];
    Some(match kind { "AVATAR" => (2 << 20, IMG), "LOGO" => (2 << 20, IMG), "ATTACHMENT" | "HOMEWORK" => (15 << 20, DOC), "DOCUMENT" => (25 << 20, DOC), "REPORT_CARD" | "CERTIFICATE" => (25 << 20, &["application/pdf"]), _ => return None })
}

fn sniff_ok(mime: &str, b: &[u8]) -> bool {
    match mime {
        "image/png" => b.starts_with(&[0x89, b'P', b'N', b'G']),
        "image/jpeg" => b.starts_with(&[0xFF, 0xD8, 0xFF]),
        "image/webp" => b.len() > 12 && &b[0..4] == b"RIFF" && &b[8..12] == b"WEBP",
        "application/pdf" => b.starts_with(b"%PDF-"),
        m if m.contains("openxmlformats") => b.starts_with(b"PK"),
        "text/plain" => !b.contains(&0),
        _ => false,
    }
}

fn clean_name(n: &str) -> String {
    let base = n.rsplit(['/', '\\']).next().unwrap_or("file");
    let s: String = base.chars().filter(|c| !c.is_control()).take(120).collect();
    let s = s.trim().trim_start_matches('.').to_string();
    if s.is_empty() { "file".into() } else { s }
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct StartReq { filename: String, mime_type: String, size_bytes: i64, kind: String, checksum_sha256: Option<String> }

async fn start(State(s): State<AppState>, ctx: Ctx, Json(r): Json<StartReq>) -> ApiResult<Response> {
    let (max, mimes) = limits(&r.kind).ok_or_else(|| ApiError::field("kind", "INVALID_VALUE", "Unknown file kind"))?;
    if matches!(r.kind.as_str(), "DOCUMENT") { ctx.require("documents.manage")?; }
    if matches!(r.kind.as_str(), "LOGO") { ctx.require("school.settings.update")?; }
    if matches!(r.kind.as_str(), "REPORT_CARD" | "CERTIFICATE") { return Err(ApiError::forbidden("These files are generated by the server")); }
    if r.kind == "HOMEWORK" && ctx.role != Role::Student && ctx.role != Role::Teacher { return Err(ApiError::forbidden("Not allowed")); }
    if !mimes.contains(&r.mime_type.as_str()) { return Err(ApiError::new(415, "UNSUPPORTED_MEDIA_TYPE", format!("Type {} is not allowed for {}", r.mime_type, r.kind))); }
    if r.size_bytes <= 0 || r.size_bytes > max { return Err(ApiError::new(413, "PAYLOAD_TOO_LARGE", format!("Maximum size for {} is {} bytes", r.kind, max))); }
    if let Some(c) = &r.checksum_sha256 { if c.len() != 64 || !c.chars().all(|x| x.is_ascii_hexdigit()) { return Err(ApiError::field("checksumSha256", "INVALID_FORMAT", "64 hex characters")); } }
    let id = Uuid::new_v4();
    sqlx::query("INSERT INTO files (id, owner_id, kind, filename, mime_type, size_bytes, checksum_sha256, storage_key) VALUES ($1,$2,$3,$4,$5,$6,$7,$8)")
        .bind(id).bind(ctx.user_id).bind(&r.kind).bind(clean_name(&r.filename)).bind(&r.mime_type).bind(r.size_bytes).bind(r.checksum_sha256.map(|c| c.to_lowercase())).bind(id.to_string()).execute(&s.db).await?;
    Ok(created(json!({ "fileId": id, "uploadUrl": format!("/api/v1/files/{id}/content"), "method": "PUT", "headers": { "Content-Type": r.mime_type }, "expiresAt": (chrono::Utc::now() + chrono::Duration::minutes(15)).to_rfc3339() })))
}

async fn owned_pending(s: &AppState, ctx: &Ctx, id: Uuid) -> ApiResult<(String, String, i64)> {
    let r: Option<(Uuid, String, String, i64, String, chrono::DateTime<chrono::Utc>)> = sqlx::query_as("SELECT owner_id, mime_type, storage_key, size_bytes, status, created_at FROM files WHERE id=$1").bind(id).fetch_optional(&s.db).await?;
    let (owner, mime, key, size, status, at) = r.ok_or_else(ApiError::not_found)?;
    if owner != ctx.user_id { return Err(ApiError::not_found()); }
    if status != "PENDING" { return Err(ApiError::conflict("FILE_NOT_PENDING", "File is not awaiting upload")); }
    if chrono::Utc::now() - at > chrono::Duration::minutes(15) { return Err(ApiError::new(410, "UPLOAD_EXPIRED", "Upload window expired; start again")); }
    Ok((mime, key, size))
}

async fn upload(State(s): State<AppState>, ctx: Ctx, Path(id): Path<Uuid>, body: Bytes) -> ApiResult<Response> {
    let (_mime, key, size) = owned_pending(&s, &ctx, id).await?;
    if body.len() as i64 != size { return Err(ApiError::new(413, "PAYLOAD_TOO_LARGE", "Uploaded size differs from the declared size")); }
    FsStorage::new(&s.cfg.storage_dir).put(&key, &body).await?;
    Ok((StatusCode::NO_CONTENT, ()).into_response())
}

async fn complete(State(s): State<AppState>, ctx: Ctx, Path(id): Path<Uuid>) -> ApiResult<Response> {
    let (mime, key, size) = owned_pending(&s, &ctx, id).await?;
    let st = FsStorage::new(&s.cfg.storage_dir);
    let bytes = st.get(&key).await.map_err(|_| ApiError::conflict("NOT_UPLOADED", "No content has been uploaded"))?;
    let declared: Option<String> = sqlx::query_scalar("SELECT checksum_sha256 FROM files WHERE id=$1").bind(id).fetch_one(&s.db).await?;
    let mut reason = None;
    if bytes.len() as i64 != size { reason = Some("size mismatch"); }
    else if !sniff_ok(&mime, &bytes) { reason = Some("content does not match the declared type"); }
    else if let Some(c) = declared { if hex::encode(Sha256::digest(&bytes)) != c { reason = Some("checksum mismatch"); } }
    if let Some(r) = reason {
        sqlx::query("UPDATE files SET status='REJECTED' WHERE id=$1").bind(id).execute(&s.db).await?;
        st.delete(&key).await;
        return Err(ApiError::field("file", "REJECTED", r));
    }
    sqlx::query("UPDATE files SET status='READY' WHERE id=$1").bind(id).execute(&s.db).await?;
    let v: Value = sqlx::query_scalar("SELECT to_jsonb(t) FROM (SELECT id, owner_id, kind, filename, mime_type, size_bytes, status, created_at FROM files WHERE id=$1) t").bind(id).fetch_one(&s.db).await?;
    Ok(ok(v))
}

/// Who may download a file. Owners always; avatars/logos any signed-in user; generated docs and uploads by rule.
pub async fn can_access(s: &AppState, ctx: &Ctx, id: Uuid) -> ApiResult<()> {
    let r: Option<(Uuid, String, String)> = sqlx::query_as("SELECT owner_id, kind, status FROM files WHERE id=$1").bind(id).fetch_optional(&s.db).await?;
    let (owner, kind, status) = r.ok_or_else(ApiError::not_found)?;
    if status != "READY" { return Err(ApiError::not_found()); }
    let yes = owner == ctx.user_id || match kind.as_str() {
        "AVATAR" | "LOGO" => true,
        "DOCUMENT" => ctx.has("documents.read") && sqlx::query_scalar::<_, bool>("SELECT EXISTS(SELECT 1 FROM documents WHERE file_id=$1 AND (visibility='ALL' OR $2))").bind(id).bind(ctx.is_staff()).fetch_one(&s.db).await?,
        "REPORT_CARD" => sqlx::query_scalar::<_, bool>("SELECT EXISTS(SELECT 1 FROM report_cards rc JOIN students st ON st.id=rc.student_id WHERE rc.file_id=$1 AND (st.user_id=$2 OR $3))").bind(id).bind(ctx.user_id).bind(ctx.has("reportcards.generate")).fetch_one(&s.db).await?,
        "CERTIFICATE" => sqlx::query_scalar::<_, bool>("SELECT EXISTS(SELECT 1 FROM certificates c JOIN students st ON st.id=c.student_id WHERE c.file_id=$1 AND (st.user_id=$2 OR $3))").bind(id).bind(ctx.user_id).bind(ctx.has("certificates.issue")).fetch_one(&s.db).await?,
        "HOMEWORK" => sqlx::query_scalar::<_, bool>("SELECT EXISTS(SELECT 1 FROM homework_submissions sb JOIN homework h ON h.id=sb.homework_id JOIN teacher_assignments a ON a.id=h.teacher_assignment_id JOIN teachers t ON t.id=a.teacher_id WHERE $1 = ANY(sb.file_ids) AND t.user_id=$2)").bind(id).bind(ctx.user_id).fetch_one(&s.db).await? || ctx.role == Role::Headmaster,
        "ATTACHMENT" => sqlx::query_scalar::<_, bool>("SELECT EXISTS(SELECT 1 FROM messages m JOIN conversation_members cm ON cm.conversation_id=m.conversation_id AND cm.user_id=$2 WHERE $1 = ANY(m.attachment_file_ids)) \
                OR EXISTS(SELECT 1 FROM notices n WHERE $1 = ANY(n.attachment_file_ids) AND n.status='PUBLISHED') OR EXISTS(SELECT 1 FROM homework h WHERE $1 = ANY(h.attachment_file_ids) AND h.status<>'DRAFT')").bind(id).bind(ctx.user_id).fetch_one(&s.db).await?,
        _ => false,
    };
    if yes { Ok(()) } else { Err(ApiError::not_found()) }
}

#[derive(Serialize, Deserialize)]
struct FileClaims { sub: Uuid, fid: Uuid, exp: i64, purpose: String }

async fn download_url(State(s): State<AppState>, ctx: Ctx, Path(id): Path<Uuid>) -> ApiResult<Response> {
    can_access(&s, &ctx, id).await?;
    let exp = chrono::Utc::now() + chrono::Duration::minutes(5);
    let token = encode(&Header::new(Algorithm::HS256), &FileClaims { sub: ctx.user_id, fid: id, exp: exp.timestamp(), purpose: "file".into() }, &EncodingKey::from_secret(s.cfg.jwt_secret.as_bytes())).map_err(|_| ApiError::internal())?;
    audit::log(&mut *s.db.acquire().await?, &ctx, "file.download_url", "file", &id.to_string(), None, None).await?;
    Ok(ok(json!({ "url": format!("/api/v1/files/{id}/download?token={token}"), "expiresAt": exp.to_rfc3339() })))
}

#[derive(Deserialize)]
struct Tok { token: String }

async fn download(State(s): State<AppState>, Path(id): Path<Uuid>, Query(q): Query<Tok>) -> ApiResult<Response> {
    let mut v = Validation::new(Algorithm::HS256); v.leeway = 0;
    let c = decode::<FileClaims>(&q.token, &DecodingKey::from_secret(s.cfg.jwt_secret.as_bytes()), &v).map_err(|_| ApiError::unauthenticated("Invalid or expired download link"))?.claims;
    if c.purpose != "file" || c.fid != id { return Err(ApiError::unauthenticated("Invalid download link")); }
    let (key, mime, name): (String, String, String) = sqlx::query_as("SELECT storage_key, mime_type, filename FROM files WHERE id=$1 AND status='READY'").bind(id).fetch_optional(&s.db).await?.ok_or_else(ApiError::not_found)?;
    let bytes = FsStorage::new(&s.cfg.storage_dir).get(&key).await?;
    let safe: String = name.chars().filter(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '-' | '_' | ' ')).collect();
    let mut h = HeaderMap::new();
    h.insert(header::CONTENT_TYPE, mime.parse().unwrap());
    h.insert(header::CONTENT_DISPOSITION, format!("attachment; filename=\"{safe}\"").parse().unwrap());
    h.insert(header::X_CONTENT_TYPE_OPTIONS, "nosniff".parse().unwrap());
    h.insert(header::CONTENT_SECURITY_POLICY, "default-src 'none'; sandbox".parse().unwrap());
    Ok((h, bytes).into_response())
}
