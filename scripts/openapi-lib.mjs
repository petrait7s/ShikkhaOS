// Extracts the HTTP surface from the Rust router (apps/api/crates/app/src/routes/*.rs) into an OpenAPI 3.1 document.
import { readdirSync, readFileSync } from "node:fs";
import path from "node:path";

const ROUTES_DIR = "apps/api/crates/app/src/routes";
const METHODS = ["get", "post", "put", "patch", "delete"];

export function extractRoutes(root = ".") {
  const dir = path.join(root, ROUTES_DIR); const out = [];
  for (const file of readdirSync(dir).filter((f) => f.endsWith(".rs") && f !== "mod.rs").sort()) {
    const src = readFileSync(path.join(dir, file), "utf8");
    // .route("/path", get(handler).post(handler2).layer(..))  — handlers may span lines
    const re = /\.route\(\s*"([^"]+)"\s*,\s*([\s\S]*?)\)\s*(?=\n\s*\.route|\n\s*\}|\s*;|\s*\.layer\(|$)/g;
    let m;
    while ((m = re.exec(src))) {
      const [, p, rest] = m;
      for (const me of METHODS) { const h = new RegExp(`(?:^|[\\s.(])${me}\\(\\s*([A-Za-z_:0-9]+)`).exec(rest); if (h) out.push({ path: p, method: me, handler: h[1], tag: file.replace(".rs", "") }); }
    }
  }
  return out.sort((a, b) => (a.path + a.method).localeCompare(b.path + b.method));
}

const PUBLIC = new Set(["/health", "/ready", "/auth/login", "/auth/refresh", "/auth/forgot-password", "/ws", "/files/{id}/download"]);

export function buildSpec(routes) {
  const lines = [
    "# GENERATED by scripts/gen-openapi.mjs from the Rust router. Do not edit by hand; run `node scripts/gen-openapi.mjs`.",
    "# Scope: complete path/method inventory with the shared envelopes. Per-endpoint request/response schemas are documented in",
    "# docs/integration/API_CONTRACT.md and enforced by the Rust integration tests and the TypeScript types (packages/types).",
    "openapi: 3.1.0", "info:", "  title: ShikkhaOS API", "  version: 1.0.0", "  description: Single-school operating system API (Rust/Axum). All responses use { data, meta? } or { error }.",
    "servers:", "  - url: /api/v1", "security:", "  - bearerAuth: []", "paths:",
  ];
  const byPath = new Map();
  for (const r of routes) { const k = r.path; if (!byPath.has(k)) byPath.set(k, []); byPath.get(k).push(r); }
  for (const [p, rs] of [...byPath].sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`  ${p}:`);
    const params = [...p.matchAll(/\{(\w+)\}/g)].map((m) => m[1]);
    if (params.length) { lines.push("    parameters:"); for (const n of params) lines.push(`      - { name: ${n}, in: path, required: true, schema: { type: string } }`); }
    for (const r of rs) {
      lines.push(`    ${r.method}:`, `      operationId: ${r.tag}_${r.handler.replace(/[^A-Za-z0-9_]/g, "_")}_${r.method}`, `      tags: [${r.tag}]`);
      if (PUBLIC.has(p)) lines.push("      security: []");
      const list = r.method === "get" && !params.length;
      if (list) lines.push("      parameters:", "        - { name: limit, in: query, schema: { type: integer, maximum: 100 } }", "        - { name: cursor, in: query, schema: { type: string } }", "        - { name: q, in: query, schema: { type: string } }");
      lines.push("      responses:", `        '${r.method === "post" && /\/(auth\/login|auth\/refresh)$/.test(p) ? 200 : 200}': { description: Success, content: { application/json: { schema: { $ref: '#/components/schemas/Envelope' } } } }`, "        default: { description: Error, content: { application/json: { schema: { $ref: '#/components/schemas/ErrorBody' } } } }");
    }
  }
  lines.push("components:", "  securitySchemes:", "    bearerAuth: { type: http, scheme: bearer, bearerFormat: JWT }", "  schemas:",
    "    Envelope: { type: object, required: [data], properties: { data: {}, meta: { $ref: '#/components/schemas/PageMeta' } } }",
    "    PageMeta: { type: object, properties: { limit: { type: integer }, nextCursor: { type: [string, 'null'] }, hasMore: { type: boolean } } }",
    "    ErrorBody: { type: object, required: [error], properties: { error: { type: object, required: [code, message], properties: { code: { type: string }, message: { type: string }, requestId: { type: string }, fieldErrors: { type: array, items: { type: object, properties: { field: { type: string }, code: { type: string }, message: { type: string } } } }, details: { type: object } } } } }");
  return lines.join("\n") + "\n";
}
